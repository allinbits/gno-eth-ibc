// Command eth-snapshot records live light-client data of an Ethereum chain
// as a Gno test of gno.land/p/aib/ibc/lightclient/ethereum: a bootstrap early
// in the current sync committee period, the period's best update, the latest
// finality update, and a storage absence proof at the finalized block.
//
// Usage: eth-snapshot -beacon URL -rpc URL -out zz_snapshot_test.gno
package main

import (
	"context"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
	"time"

	"github.com/gnolang/gno-eth-ibc/relayer/beacon"
	"github.com/gnolang/gno-eth-ibc/relayer/ethgno"
)

func main() {
	var (
		beaconURL = flag.String("beacon", "https://lodestar-sepolia.chainsafe.io", "beacon node API")
		rpcURL    = flag.String("rpc", "https://ethereum-sepolia-rpc.publicnode.com", "execution JSON-RPC")
		chainID   = flag.Uint64("chain-id", 11155111, "execution chain ID")
		account   = flag.String("account", "0x7b79995e5f793A07Bc00c21412e50Ecae098E7f9", "account to prove absent storage of (Sepolia WETH)")
		out       = flag.String("out", "zz_snapshot_test.gno", "output Gno test file")
		name      = flag.String("name", "Sepolia", "test name suffix")
	)
	flag.Parse()
	ctx, cancel := context.WithTimeout(context.Background(), 25*time.Minute)
	defer cancel()
	src, err := snapshot(ctx, beacon.New(*beaconURL), ethgno.NewExecution(*rpcURL), *chainID, *account, *name)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// The Eureka router's commitments mapping slot; any 32 bytes work for an
// absence proof.
var commitmentSlot = mustHex("1260944489272988d9df285149b5aa1b0f48f2136d6f416159f840a3e0747600")

func snapshot(ctx context.Context, bc *beacon.Client, ex *ethgno.Execution, chainID uint64, account, name string) ([]byte, error) {
	params, err := ethgno.ReadChainParams(ctx, bc)
	if err != nil {
		return nil, err
	}
	slotsPerPeriod := params.SlotsPerEpoch * params.EpochsPerSyncCommitteePeriod

	// Beacon nodes only serve bootstraps at recent finalized checkpoints.
	bootRoot, err := bc.BlockRoot(ctx, "finalized")
	if err != nil {
		return nil, err
	}
	boot, err := bc.Bootstrap(ctx, bootRoot)
	if err != nil {
		return nil, err
	}
	bootSlot := uint64(boot.Header.Beacon.Slot)
	period := bootSlot / slotsPerPeriod

	// The period's best update reveals the next sync committee; it is
	// usually older than the bootstrap, which the client accepts for that
	// purpose alone.
	updates, err := bc.Updates(ctx, period, 1)
	if err != nil || len(updates) != 1 {
		return nil, fmt.Errorf("period %d update: %v", period, err)
	}
	periodUpdate := updates[0]
	if periodUpdate.NextSyncCommittee == nil {
		return nil, fmt.Errorf("period update has no next sync committee")
	}

	// Then wait for finality to move past the bootstrap.
	var fin beacon.LightClientUpdate
	for {
		if fin, err = bc.FinalityUpdate(ctx); err != nil {
			return nil, err
		}
		if uint64(fin.FinalizedHeader.Beacon.Slot) > bootSlot {
			break
		}
		log.Printf("waiting for finality past slot %d (at %d)", bootSlot, fin.FinalizedHeader.Beacon.Slot)
		select {
		case <-ctx.Done():
			return nil, ctx.Err()
		case <-time.After(30 * time.Second):
		}
	}
	if uint64(fin.AttestedHeader.Beacon.Slot)/slotsPerPeriod != period {
		return nil, fmt.Errorf("the period ended while waiting; run again")
	}

	bootExec, err := ex.Header(ctx, boot.Header.BlockHash())
	if err != nil {
		return nil, fmt.Errorf("bootstrap execution header: %w", err)
	}
	execHeader := func(u beacon.LightClientUpdate) ([]byte, ethgno.ExecHeader, error) {
		h, err := ex.Header(ctx, u.FinalizedHeader.BlockHash())
		if err != nil {
			return nil, h, err
		}
		if u.FinalizedHeader.Execution != nil {
			return nil, h, nil // pre-Gloas: the payload header is in the update
		}
		return h.RLP, h, nil
	}
	periodRLP, _, err := execHeader(periodUpdate)
	if err != nil {
		return nil, err
	}
	finRLP, finExec, err := execHeader(fin)
	if err != nil {
		return nil, err
	}

	path := []byte("gno-eth-ibc snapshot absent key")
	// Public RPCs often keep too little state history to prove the finalized
	// block; the proof is then left out (the recorded eureka fixtures cover
	// storage proofs).
	proof, proofErr := ex.GetProof(ctx, account, ethgno.CommitmentSlot(path, commitmentSlot), finExec.Number)
	if proofErr != nil {
		log.Printf("leaving out the storage proof: %v", proofErr)
	}

	routerAddr := mustHex(strings.TrimPrefix(account, "0x"))
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gno-eth-ibc/relayer/cmd/eth-snapshot on %s. DO NOT EDIT.\n\n", time.Now().UTC().Format(time.RFC3339))
	fmt.Fprintf(&b, "package ethereum_test\n\nimport (\n\t\"encoding/hex\"\n\t\"testing\"\n\n\tethereum %q\n\t\"gno.land/p/aib/ibc/types/v0\"\n)\n\n", ethgno.ImportPath)
	b.WriteString(ethgno.Helpers)
	fmt.Fprintf(&b, `
// Test%[1]s replays live %[1]s data: a bootstrap at slot %[2]d, the best
// update of sync committee period %[3]d (which only reveals the next sync
// committee), and the finality update to slot %[4]d (execution block %[6]d),
// with, when the RPC could serve it, an absence proof in the storage of %[5]s.
func Test%[1]s(t *testing.T) {
	c := ethereum.NewEthLightClient()
	if err := c.Initialize(%[7]s, %[8]s); err != nil {
		t.Fatal(err)
	}
`, name, boot.Header.Beacon.Slot, period, fin.FinalizedHeader.Beacon.Slot, account, finExec.Number,
		ethgno.ClientState(params, chainID, routerAddr, commitmentSlot, uint64(boot.Header.Beacon.Slot), bootExec.Number),
		ethgno.ConsensusState(boot, bootExec.StateRoot, bootExec.Timestamp))

	step := func(u beacon.LightClientUpdate, trusted, wantLatest uint64, rlp []byte) {
		now := params.GenesisTime + (uint64(u.SignatureSlot)+1)*params.SecondsPerSlot
		fmt.Fprintf(&b, "\tapplyUpdate(t, c, %d, %d, %s)\n", now, wantLatest,
			ethgno.Header(u, boot.CurrentSyncCommittee, false, trusted, rlp))
	}
	step(periodUpdate, bootSlot, bootSlot, periodRLP)
	step(fin, bootSlot, uint64(fin.FinalizedHeader.Beacon.Slot), finRLP)

	if proofErr == nil {
		fmt.Fprintf(&b, `
	err := c.VerifyNonMembershipProof(types.NewHeight(0, %d), %s,
		types.MerklePath{KeyPath: [][]byte{[]byte(%q)}})
	if err != nil {
		t.Fatal(err)
	}
`, fin.FinalizedHeader.Beacon.Slot, ethgno.MembershipProof(proof), path)
	} else {
		b.WriteString("\t_ = types.Height{}\n")
	}
	b.WriteString("}\n")

	b.WriteString(`
func applyUpdate(t *testing.T, c *ethereum.EthLightClient, now, wantLatest uint64, h *ethereum.Header) {
	t.Helper()
	testing.SetContext(testing.Context{Time: time.Unix(int64(now), 0)})
	if err := c.VerifyClientMessage(h); err != nil {
		t.Fatalf("update at signature slot %d: %v", h.ConsensusUpdate.SignatureSlot, err)
	}
	if c.CheckForMisbehaviour(h) {
		t.Fatal("update reported as misbehaviour")
	}
	c.UpdateState(h)
	if c.LatestHeight().RevisionHeight != wantLatest {
		t.Fatalf("latest slot %d, want %d", c.LatestHeight().RevisionHeight, wantLatest)
	}
}
`)
	src := strings.Replace(b.String(), "\t\"testing\"\n", "\t\"testing\"\n\t\"time\"\n", 1)
	out, err := format.Source([]byte(src))
	if err != nil {
		return []byte(src), fmt.Errorf("format: %w", err)
	}
	return out, nil
}

func mustHex(s string) []byte {
	b, err := hexDecode(s)
	if err != nil {
		panic(err)
	}
	return b
}
