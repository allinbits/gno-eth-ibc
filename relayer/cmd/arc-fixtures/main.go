// Command arc-fixtures writes the testnet fixture of the gno.land Arc light
// client (gno-realms gno.land/p/aib/ibc/lightclient/arc/testing/v0,
// testnet.gno) from live Arc testnet data: a client created at one block, and an update to a later block,
// certified by its child's commit certificate. The update carries the
// registry's set nodes too, so the test can also exercise reading a set in
// an update (by forgetting the trusted registry root).
package main

import (
	"context"
	"encoding/hex"
	"flag"
	"fmt"
	"log"
	"os"
	"strings"
	"time"

	"github.com/ethereum/go-ethereum/common"

	"github.com/gnolang/gno-eth-ibc/relayer/arc"
)

func main() {
	certRPC := flag.String("cert-rpc", arc.TestnetCertRPC, "RPC serving arc_getCertificate")
	proofRPC := flag.String("proof-rpc", arc.TestnetProofRPC, "RPC serving eth_getProof at latest")
	out := flag.String("out", "testnet.gno", "output file")
	gap := flag.Duration("gap", 5*time.Second, "time between the two snapshots")
	flag.Parse()
	ctx := context.Background()

	c, err := arc.Dial(ctx, *certRPC, *proofRPC)
	if err != nil {
		log.Fatal(err)
	}
	s0, err := c.LatestSnapshot(ctx, arc.TestnetRegistry, common.Hash{}, common.Address{}, nil)
	if err != nil {
		log.Fatal(err)
	}
	log.Printf("creation block %d (%d validators' slots, %d nodes)", s0.Number, len(s0.Registry.Values), len(s0.Registry.Nodes))
	time.Sleep(*gap)
	// common.Hash{} as the known root: include the set, which the test
	// can use or ignore.
	s1, err := c.LatestSnapshot(ctx, arc.TestnetRegistry, common.Hash{}, common.Address{}, nil)
	if err != nil {
		log.Fatal(err)
	}
	cert, err := c.Certificate(ctx, s1.Number+1)
	if err != nil {
		log.Fatal(err)
	}
	certHeader, certRLP, err := c.Header(ctx, s1.Number+1)
	if err != nil {
		log.Fatal(err)
	}
	if certHeader.Hash() != cert.BlockHash {
		log.Fatalf("certificate block hash %s differs from block %d's %s", cert.BlockHash, s1.Number+1, certHeader.Hash())
	}
	log.Printf("update block %d, certified by %d (%d signatures)", s1.Number, cert.Height, len(cert.Signatures))

	p := arc.ClientParams{
		ChainID: arc.TestnetChainID, TrustingPeriod: 14 * 24 * 3600, MaxClockDrift: 90,
		TrustNumerator: 1, TrustDenominator: 3,
		Router:         common.HexToAddress("0x00000000000000000000000000000000000000aa"),
		CommitmentSlot: common.Hash{},
		Registry:       arc.TestnetRegistry,
	}
	creation := arc.EncodeCreation(p, s0)
	header := arc.EncodeHeader(s0.Number, cert, certRLP, s1)
	sameSet := s0.Registry.StorageRoot == s1.Registry.StorageRoot

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gno-eth-ibc/relayer/cmd/arc-fixtures on %s. DO NOT EDIT.\n\n", time.Now().UTC().Format(time.RFC3339))
	b.WriteString("package testing\n\n")
	fmt.Fprintf(&b, "// Arc testnet (chain %d): a client created at block %d (Creation), updated\n", arc.TestnetChainID, s0.Number)
	fmt.Fprintf(&b, "// to block %d (Header) by the certificate of block %d (%d signatures),\n", s1.Number, cert.Height, len(cert.Signatures))
	b.WriteString("// verified at Time. The header carries the registry's set nodes even when\n")
	b.WriteString("// the registry did not change (SameRegistry).\n")
	fmt.Fprintf(&b, "const (\n\tCreationHeight = %d\n\tUpdateHeight   = %d\n\tTime           = %d\n\tSameRegistry   = %v\n)\n\n",
		s0.Number, s1.Number, certHeader.Time+2, sameSet)
	fmt.Fprintf(&b, "var Creation = hx(%q)\n\nvar Header = hx(%q)\n", hex.EncodeToString(creation), hex.EncodeToString(header))
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s (%d + %d bytes of messages)", *out, len(creation), len(header))
}
